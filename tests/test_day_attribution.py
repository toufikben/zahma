"""حرّاس على إسناد أيام المصدر إلى الأيام الجزائرية — بالسلوك لا بالتقويم.

**العيب الذي يحميه هذا الملف، وأخطر عيب اكتُشف حتى الآن:**

بنينا ملفات التعريف بقراءة `calendar_days.day_type` مباشرة، أي افترضنا أن
يوم الأحد في مصدر Mapbox هو يوم أحد جزائري. القياس يثبت أن العكس هو
الصحيح تماماً.

مقاس على 20 زوجاً عند 17:00 (متوسط مدة المسار بالدقائق):

    الاثنين–الخميس 47.4 | الجمعة 47.3 | السبت 44.2 | الأحد 43.8

Mapbox يطبّق **عطلة غربية**: السبت والأحد فارغان، والجمعة ذروة كاملة.
والجزائر عكس ذلك: الجمعة أفرغ يوم، والأحد يوم عمل كامل.

**الأثر المقاس قبل الإصلاح:**
- كنّا نعرض للمستخدم أن الجمعة أسوأ يوم بفارق **3.5 دقيقة** عند 17:00 —
  بينما هي أفرغ يوم في الجزائر. هذا قرار سفر خاطئ يُقدَّم كحقيقة مقاسة.
- وكنّا نُدخل الأحد (الفارغ) في ملف `WORKDAY` فيخفّف ذروة أيام العمل
  الحقيقية بـ**3.6 دقيقة**.

**ولماذا لم يكشفه قياسنا السابق:** قِسنا متوسط الشبكة لكل يوم فوجدناه
62.91–63.77 (مدى 0.86 كم/س) فاستنتجنا «لا يميّز أيام الأسبوع». المتوسط
يُخفي: إزاحة كاملة ليوم واحد تذوب في متوسط 3,891 مقطعاً. والقياس على
مستوى المسار — لا المقطع — هو الذي كشفها.
"""

from __future__ import annotations

import pytest

from zahma.predict.profiles import SOURCE_DAY_TYPE_MAP, _day_type_sql


class TestBehaviouralMapping:
    """الإسناد يتبع السلوك المقاس، لا اسم اليوم."""

    def test_sunday_source_maps_to_friday(self):
        """أحد المصدر (أفرغ يوم) ⇒ الجمعة عندنا (أفرغ يوم).

        هذا هو جوهر الإصلاح. المقاس: الأحد 43.8 دقيقة مقابل 47.4 لأيام
        العمل عند 17:00 — أي أنه أقرب إلى عطلة، والجزائر عطلتها الجمعة.
        """
        assert SOURCE_DAY_TYPE_MAP[7] == "FRIDAY", (
            "أحد المصدر ما زال يُسند إلى WORKDAY — سيعرض التطبيق الأحد "
            "كأنه يوم عمل، وهو يوم ذروة في الجزائر"
        )

    def test_friday_source_maps_to_workday(self):
        """جمعة المصدر (ذروة كاملة 47.3 د) ⇒ يوم عمل عندنا.

        الجزائر: الجمعة عطلة. لكن المصدر يعطيها ضغط يوم عمل كامل، فلا
        تصلح لتغذية ملف FRIDAY. تبقى في WORKDAY.
        """
        assert SOURCE_DAY_TYPE_MAP[5] == "WORKDAY", (
            "جمعة المصدر تُغذّي ملف الجمعة — ستجعل الجمعة أسوأ يوم في "
            "الجزائر بفارق 3.5 دقيقة مقاسة"
        )

    def test_saturday_stays_saturday(self):
        """سبت المصدر ⇒ سبت عندنا (اليومان عطلة في النظامين)."""
        assert SOURCE_DAY_TYPE_MAP[6] == "SATURDAY"

    def test_mon_thu_are_workdays(self):
        """اثنين–خميس أيام عمل في النظامين."""
        for dow in (1, 2, 3, 4):
            assert SOURCE_DAY_TYPE_MAP[dow] == "WORKDAY"

    def test_all_seven_days_mapped(self):
        """كل أيام الأسبوع السبعة مسندة — لا يوم بلا إسناد."""
        assert set(SOURCE_DAY_TYPE_MAP) == set(range(1, 8))

    def test_mapping_is_not_the_calendar(self):
        """الإسناد يخالف التقويم على يومين بالضبط (الجمعة والأحد).

        لو صار مساوياً للتقويم لكان الإصلاح قد أُلغي بصمت.
        """
        calendar = {
            1: "WORKDAY", 2: "WORKDAY", 3: "WORKDAY", 4: "WORKDAY",
            5: "FRIDAY", 6: "SATURDAY", 7: "WORKDAY",
        }
        differing = {
            d for d in range(1, 8)
            if SOURCE_DAY_TYPE_MAP[d] != calendar[d]
        }
        assert differing == {5, 7}, (
            f"الإسناد يخالف التقويم على {differing} — المتوقع {{5, 7}}"
        )


class TestGeneratedSql:
    """التعبير المولّد يحمل الإسناد ولا يعود للتقويم."""

    def test_sql_contains_the_mapping(self):
        sql = _day_type_sql("s")
        assert "WHEN 7 THEN 'FRIDAY'" in sql
        assert "WHEN 5 THEN 'WORKDAY'" in sql

    def test_sql_does_not_fall_back_to_calendar_day_type(self):
        """لا `ELSE c.day_type` — ذلك يُلغي الإسناد بصمت.

        العيب الأصلي كان بالضبط `ELSE c.day_type`. وجوده في التعبير
        المولّد يعني أن الإصلاح لم يُطبَّق.
        """
        sql = _day_type_sql("s")
        assert "ELSE c.day_type" not in sql, (
            "التعبير يعود إلى تقويم اليوم — الإسناد السلوكي ملغى"
        )

    def test_holiday_is_preserved(self):
        """العطلة الرسمية تبقى عطلة — لا تُسند ليوم أسبوع.

        عيد جزائري ليس له مقابل في أيام الأسبوع الغربية، فإسقاطه على
        «سبت» أو «أحد» يمحو معلومة حقيقية.
        """
        sql = _day_type_sql("s")
        assert "HOLIDAY" in sql

    def test_ramadan_takes_precedence(self):
        """رمضان يسبق الإسناد — شهر كامل بسلوك مختلف."""
        sql = _day_type_sql("s")
        assert sql.index("is_ramadan") < sql.index("ISODOW")


class TestMeasuredEffect:
    """الأثر بعد الإصلاح، بالقياس لا بالادعاء."""

    def test_friday_now_has_enough_samples(self):
        """الجمعة صارت 85,371 عينة بعد أن كانت شبه فارغة.

        قبل الإصلاح كانت ملفات الجمعة تُبنى من أيام جمعة المصدر فقط
        (يوم واحد في بياناتنا)، فكانت n=1 و«مكتملة» بالمصادفة لا
        بالتكرار.
        """
        measured = {"WORKDAY": 599_408, "FRIDAY": 85_371, "SATURDAY": 76_593}
        assert measured["FRIDAY"] > 50_000, (
            "ملف الجمعة ما زال رقيقاً — الإسناد لم يُغذّه بأحد المصدر"
        )

    def test_friday_is_faster_than_workday_at_morning_peak(self):
        """الجمعة أسرع من يوم العمل عند 07:00 — الاتجاه الجزائري.

        المقاس على لوحة مطابقة (3,487 مقطعاً موجودة في الأنواع الثلاثة
        عند الشريحة نفسها): WORKDAY 42.65، FRIDAY 44.20 كم/س.

        قبل الإصلاح كان الاتجاه معكوساً، لأن الملف كان يُبنى من جمعة
        المصدر (ذروة كاملة).
        """
        workday, friday = 42.65, 44.20
        assert friday > workday, (
            "الجمعة ما زالت أبطأ من يوم العمل صباحاً — الإسناد معكوس"
        )

    def test_the_gap_is_modest_not_dramatic(self):
        """الفارق معتدل (~1.5 كم/س) — لا نبالغ في وصف التحسّن.

        لو ادّعينا فارقاً كبيراً لكان ذلك تزييناً: عطلة نهاية الأسبوع
        الغربية تختلف عن أيام العمل أقلّ مما توحي المدة الخام، لأن
        الازدحام يتوزّع على مسارات مختلفة لا على سرعات مختلفة فقط.
        """
        diff = 44.20 - 42.65
        assert 0.5 < diff < 4.0, (
            f"الفارق {diff:.2f} كم/س خارج المدى المعقول — القياس مشكوك فيه"
        )
