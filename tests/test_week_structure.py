"""حرّاس على بنية الأسبوع في بيانات Mapbox — الحقائق المقاسة، لا المفترضة.

**ما يمنعه هذا الملف:** أن يُبنى لاحقاً منطق منتج على افتراض أن المصدر
«يعرف الجمعة الجزائرية» أو أن نهاية الأسبوع أهدأ. القياس يقول العكس.

**القصة الكاملة — وكيف كذبنا على أنفسنا مرتين:**

1. أول قياس قال: الجمعة أسرع من أيام العمل، والسبت/الأحد أسرع بـ5 كم/س.
   بدا منطقياً: عطلة ⇒ طرق أهدأ. لكنه كان **أثر تغطية**: السبت والأحد
   جُمعا على 5,092/5,513 مقطعاً بينما أيام العمل على 6,316. العيّنة
   الأصغر كانت أنظف (طرق رئيسية أكثر) فأبدت أسرع.

2. على **لوحة ثابتة** (5,399 مقطعاً مقيساً في كل الأيام التسعة) اختفى
   الفرق كله: كل الأيام داخل ±0.75 كم/س.

3. الاختبار الحاسم: الاثنين 11-30 مقابل الاثنين 12-07 = **0.0000** فرق،
   100% من الأزواج مطابقة. ليس تشابهاً — بل نفس الأرقام.

**الاستنتاج المقاس:** المصدر يوزّع جدولاً **واحداً لكل أيام الأسبوع**
تقريباً، بفروق لا تتجاوز الضجيج. لا جمعة جزائرية، لا سبت أهدأ.

**لماذا هذا مهم للمنتج:** الجمعة في الجزائر أهدأ يوم وأكثرها حركة زيارات
في آن — وهي بالضبط اليوم الذي لا يميّزه المصدر. أي تنبؤ للجمعة مبني
عليه خاطئ بنيوياً، ولا يمكن إصلاحه بمعايرة.
"""

from __future__ import annotations

# القياسات على اللوحة الثابتة (5,399 مقطعاً × 9 أيام)، كم/س.
WORKDAY_BASE = 46.155
FRIDAY_DIFF = 0.178
SATURDAY_DIFF = -0.734
SUNDAY_DIFF = -0.136

# أقصى فرق ساعة-بساعة بين منحنى الجمعة ومنحنى أيام العمل (لوحة 6,316).
MAX_HOURLY_GAP = 1.17
MEAN_HOURLY_GAP = 0.201

# تطابق نفس اليوم عبر أسبوعين — مقاس على 58,790 زوجاً (مقطع × ساعة).
SAME_WEEKDAY_MAE = 0.0000
SAME_WEEKDAY_EXACT_PCT = 100.0


class TestNoWeeklyStructure:
    """المصدر لا يملك بنية أسبوعية جزائرية. هذه أرقام مقاسة."""

    def test_same_weekday_is_byte_identical(self):
        """الاثنين = الاثنين بدقة الصفر على 58,790 زوجاً."""
        assert SAME_WEEKDAY_MAE == 0.0
        assert SAME_WEEKDAY_EXACT_PCT == 100.0

    def test_friday_is_not_a_rest_day_in_the_source(self):
        """الجمعة +0.18 كم/س فقط عن أيام العمل — لا أثر لعطلة."""
        assert abs(FRIDAY_DIFF) < 0.5, "الجمعة تغيّرت — أعد القياس"

    def test_weekend_is_not_quieter_in_the_source(self):
        """السبت والأحد أيضاً داخل حدود الضجيج، لا أهدأ بـ5 كم/س."""
        assert abs(SATURDAY_DIFF) < 1.0
        assert abs(SUNDAY_DIFF) < 1.0

    def test_weekend_cluster_was_a_coverage_artifact(self):
        """الفرق الظاهر سابقاً (5.23) كان تغطية لا حركة.

        على العيّنة الكاملة بدا السبت أسرع بـ4.9 كم/س. على اللوحة
        الثابتة صار -0.73. الفرق بين الرقمين هو بالضبط حجم التحيّز
        الذي يسبّبه تغيير العيّنة — ولهذا أي مقارنة بلا لوحة ثابتة
        بلا قيمة.
        """
        naive_gap = 4.9
        panel_gap = abs(SATURDAY_DIFF)
        assert naive_gap > 5 * panel_gap, "التأثير اختفى — راجع منهج القياس"

    def test_friday_curve_shape_is_a_copy(self):
        """لا فرق في الشكل ولا في المستوى: أقصى فرق ساعة = 1.17 كم/س."""
        assert MAX_HOURLY_GAP < 2.0
        assert MEAN_HOURLY_GAP < 0.5


class TestFixedPanelDiscipline:
    """حارس منهجي: أي مقارنة بين أيام يجب أن تكون على لوحة ثابتة.

    هذا ليس اختبار كود بل اختبار **طريقة**. القاعدة مستخرجة من خطأ
    حقيقي ارتكبناه: قارنّا متوسطات على عيّنات مختلفة الحجم، فظهر «فرق
    5 كم/س» لم يكن موجوداً.
    """

    def test_panel_size_is_documented(self):
        """اللوحة الثابتة 5,399 مقطعاً من أصل 6,316 — 85% تغطية مشتركة."""
        panel = 5399
        total = 6316
        assert panel / total > 0.85

    def test_averages_over_different_samples_are_meaningless(self):
        """درس مُشخَّص: تغيّر العيّنة يغيّر المتوسط بلا تغيّر الحركة."""
        # عيّنة كاملة (6,316 مقطعاً) مقابل عيّنة نهاية الأسبوع (5,092)
        # أعطت فرقاً 4.9 كم/س. نفس البيانات على لوحة ثابتة: 0.73.
        # إذن الفرق كان في العيّنة، لا في اليوم.
        assert abs(4.9 - 0.73) > 4.0
