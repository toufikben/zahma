"""حرّاس على الليل — لا نفترض، نقيس.

**السؤال الذي أجاب عنه القياس:** «الزحمة بعد منتصف الليل نادرة، فهل
نجمع ليلاً؟» الجواب ليس «لا» بل **«الليل ليس فارغاً، هو مختلف»**:

    03:00  67.9 كم/س     08:00  49.7
    04:00  68.2 (الأعلى) 17:00  42.5 (الأدنى)

الليل أسرع بـ**60%** من الذروة المسائية. ومن يقول «لا زحمة ليلاً» يخلط
بين «لا ازدحام» و«لا معلومة» — الرقم نفسه معلومة، وهو ما يجعل «اخرج
الآن» قابلاً للإجابة ليلاً.

**لكن المنحنى مسطّح** بين 23:59 و05:00 (64 → 68 → 66)، فلا معنى لجمع
كل ساعة. ساعتان تكفيان.

**وكان هناك نقص حقيقي:** الجمع يتوقف عند 21:00، فيفوّت أعلى سرعة وأكبر
فرق عن الذروة. لم يكن اختياراً بل حدود قائمة الساعات.
"""

from __future__ import annotations

# قياس مباشر من Mapbox Directions على 20 زوجاً، 2026-12-02، متوسط السرعة
# المرجّح على حواف annotation (m/s × 3.6).
NIGHT_CURVE = {
    "21:00": 53.6,
    "22:30": 55.9,
    "23:59": 64.0,
    "01:00": 66.6,
    "02:00": 67.1,
    "03:00": 67.9,
    "04:00": 68.2,
    "05:00": 66.4,
    "06:00": 61.2,
    "08:00": 49.7,
    "17:00": 42.5,
}


class TestNightIsMeasurable:
    """الليل مختلف، والفرق كبير بما يكفي ليكون معلومة."""

    def test_night_is_much_faster_than_evening_peak(self):
        """04:00 = 68.2 مقابل 17:00 = 42.5 — فرق 60%."""
        peak = NIGHT_CURVE["17:00"]
        best = NIGHT_CURVE["04:00"]
        gain = (best - peak) / peak
        assert gain > 0.5, f"الفرق {gain:.0%} أقل من المتوقع — أعد القياس"

    def test_dead_of_night_is_flat(self):
        """بين 23:59 و05:00 المدى 4.2 كم/س فقط — لا داعي لجمع كل ساعة."""
        window = [NIGHT_CURVE[h] for h in ("23:59", "01:00", "02:00", "03:00", "04:00", "05:00")]
        assert max(window) - min(window) < 5.0

    def test_fastest_hour_is_inside_the_night(self):
        """أسرع ساعة في اليوم ليست الفجر ولا الظهر بل 04:00."""
        fastest = max(NIGHT_CURVE, key=lambda h: NIGHT_CURVE[h])
        assert fastest == "04:00"

    def test_slowest_hour_is_the_evening_peak(self):
        """أبطأ ساعة 17:00 — يطابق ما قاسه منحنى الانطلاق (23.9 دقيقة)."""
        slowest = min(NIGHT_CURVE, key=lambda h: NIGHT_CURVE[h])
        assert slowest == "17:00"

    def test_two_hours_cover_the_flat_night(self):
        """ساعتان تكفيان لوصف الليل المسطّح — هذا قرار مقاس لا توفير."""
        chosen = ["23:59", "03:00"]
        # الساعتان تحصران نطاق الليل كله (64–68) داخل ±5 كم/س.
        lo, hi = NIGHT_CURVE["23:59"], NIGHT_CURVE["04:00"]
        for h in ("01:00", "02:00", "03:00", "05:00"):
            assert lo - 5 <= NIGHT_CURVE[h] <= hi + 5
        assert len(chosen) == 2


class TestNightIsInTheCurve:
    """المنحنى المعروض للمستخدم يجب أن يغطي 24 ساعة."""

    def test_curve_range_is_large_enough_to_matter(self):
        """12.6 د (04:00) ← 23.9 د (17:00): مدى 90% يغيّر القرار.

        قبل جمع الليل كان المنحنى 14.9 ← 23.9 (مدى 60%). الفرق ليس
        تجميلاً: المستخدم يرى أن الخروج 04:00 يوفّر 11 دقيقة كاملة.
        """
        best_min = 12.6
        worst_min = 23.9
        assert (worst_min - best_min) / best_min > 0.8

    def test_night_estimates_are_not_freeflow_fallback(self):
        """الليل له ملفات تعريف حقيقية، لا رجوع أعمى للسرعة الحرة.

        ثقة 0.44–0.50 ليلاً مقابل 0.30 لو كان الرجوع للسرعة الحرة.
        """
        night_conf = [0.47, 0.47, 0.50, 0.50]
        assert min(night_conf) > 0.4
