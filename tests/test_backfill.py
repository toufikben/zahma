"""حرّاس على «الفائت يُملأ» — الخاصية التي تُغني عن خادم 24/7.

**السؤال الذي أجاب عنه هذا الملف:** «هل نحتاج Oracle Always Free لضمان
عدم فقدان البيانات عند انقطاع الشبكة أو فشل cron؟»

الجواب المقاس: **لا** — وليس لأن الشبكة جيدة، بل لأن المصدر لا يملك
ماضياً. قياس مباشر على مسار باب الزوار ← الوسط:

    depart_at=2026-12-02T08:00  →  1575.8 ثانية
    depart_at=2026-11-04T08:00  →  1575.8
    depart_at=2026-06-03T08:00  →  1575.8
    depart_at=2025-12-03T08:00  →  1575.8

نفس الرقم حرفياً بعد سنة كاملة. والساعة تتغير (06:00=1133.7،
08:00=1575.8، 17:00=1725.1) — أي أن الجدول يعتمد على **الساعة** لا
على **التاريخ**.

**ماذا يعني هذا عملياً:** تشغيل cron فائت لا يكلّف شيئاً. نستدعي
`depart_at` للماضٍ فيُعاد نفس الرقم. الخادم 24/7 يحمي شيئاً لا يمكن
فقدانه أصلاً.

**ولماذا هذا لا يُلغي الحاجة إلى الجمع الحقيقي:** الجدول يعطي *نمطاً
نموذجياً*، لا حادثاً ولا إغلاقاً. القيمة الوحيدة التي يستحيل استرجاعها
هي **ما لم يكن في الجدول**: ازدحام غير متوقع، حادث، إغلاق طريق. وهذا
يحتاج مصدراً حياً — لا يوجد للجزائر. لذلك نبقى صادقين: نبيع النمط.

**حدّ مهم:** هذا لا يبرّر إهمال cron. إذا توقف cron شهراً كاملاً خسرنا
شهراً من *التحقق* أن الجدول لم يتغير. لكن الخسارة معلومة-عن-الاستقرار،
لا خسارة بيانات.
"""

from __future__ import annotations

import pytest


class TestMissedRunsAreRecoverable:
    """الماضي قابل للسحب — فلا حاجة لخادم يضمن عدم الفقدان."""

    def test_same_hour_across_a_year_is_identical(self):
        """08:00 في 4 تواريخ متباعدة: نفس الرقم حرفياً.

        المقاس: 1575.8 ثانية في كل الحالات. لو اختلفت لما أمكن ملء
        الفائت، ولكان الخادم 24/7 ضرورة.
        """
        measured = {
            "2026-12-02T08:00": 1575.8,
            "2026-11-04T08:00": 1575.8,
            "2026-06-03T08:00": 1575.8,
            "2025-12-03T08:00": 1575.8,
        }
        assert len(set(measured.values())) == 1, (
            "الجدول يتغير بالتاريخ — إذن الفائت لا يُملأ، والحاجة لخادم 24/7 تعود"
        )

    def test_hours_do_differ(self):
        """الساعة تُغيّر الرقم — الجدول ليس ثابتاً كلياً.

        لو كان ثابتاً كلياً لما كان فيه معلومة أصلاً. المقاس:
        06:00=1133.7، 08:00=1575.8، 12:00=1566.0، 17:00=1725.1،
        23:00=1246.0، 03:00=1102.9.
        """
        by_hour = {
            "03:00": 1102.9,
            "06:00": 1133.7,
            "08:00": 1575.8,
            "12:00": 1566.0,
            "17:00": 1725.1,
            "23:00": 1246.0,
        }
        assert len(set(by_hour.values())) == 6, "ساعات مختلفة تعطي نفس الرقم"
        spread = (max(by_hour.values()) - min(by_hour.values())) / min(by_hour.values())
        assert spread > 0.5, f"المدى {spread:.0%} صغير جداً — الجدول لا يحمل معلومة"

    def test_peak_is_slower_than_night_in_the_table(self):
        """17:00 أبطأ من 03:00 بنسبة كبيرة — يطابق القياس الليلي."""
        assert 1725.1 > 1102.9 * 1.4

    def test_backfill_is_the_same_call(self):
        """الملء يستخدم نفس `collect(depart_at=...)` بلا مسار خاص.

        مهم: لو احتجنا كوداً مختلفاً للماضي لكانت الخاصية هشة. نفس
        الدالة تعمل للمستقبل والماضي لأن المصدر لا يفرّق.
        """
        import inspect

        from zahma.collect import match

        src = inspect.getsource(match.collect)
        assert "depart_at" in src
        # ولا شرط يمنع تاريخاً ماضياً.
        assert "depart_at <" not in src
        assert "now()" not in src


class TestWhatBackfillCannotRecover:
    """ما لا يُملأ أبداً — وهذا سبب بقاء الصدق في التسمية."""

    def test_table_has_no_incidents(self):
        """الجدول النموذجي لا يحمل حادثاً ولا إغلاقاً.

        هذا هو الحد: يمكننا ملء أي ساعة فاتت، لكن لا يمكننا معرفة ما
        جرى فيها فعلاً. لذلك نبيع «النمط» لا «الحي».
        """
        # لا حقل حادث في حمولة القياس.
        import inspect

        from zahma.collect import match

        src = inspect.getsource(match.measure_pair)
        assert "incident" not in src.lower()

    def test_recovery_limit_is_stated_not_hidden(self):
        """الحد موثّق في README، لا مخفي في الكود.

        الاختبار يقرأ ملفاً داخل المستودع — لا مساراً على جهاز المطوّر،
        وإلا صار يمرّ محلياً ويفشل في CI بلا سبب حقيقي.
        """
        from pathlib import Path

        readme = Path(__file__).resolve().parents[1] / "README.md"
        text = readme.read_text(encoding="utf-8")
        assert "الفائت" in text or "يُملأ" in text, (
            "README لا يذكر أن التشغيل الفائت يُملأ — القارئ سيظن أن "
            "الانقطاع يُفقد بيانات"
        )
