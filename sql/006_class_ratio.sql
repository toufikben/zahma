-- 006: نسبة الأداء في أولوية الصنف
--
-- **المشكلة التي يحلّها هذا الملف:** أولوية الصنف كانت تأخذ وسيط
-- **السرعة المطلقة** لكل (صنف، شريحة). هذا يخلط بين مقطعين من نفس
-- الصنف لكن سرعتيهما الحرة مختلفة جذرياً: residential سرعته الحرة
-- 40 كم/س وresidential آخر 60 كم/س يتصرفان بشكل مختلف، والوسيط
-- المطلق يعطيهما نفس الرقم.
--
-- **الحل:** نخزّن أيضاً وسيط **نسبة الأداء** = السرعة الفعلية ÷ السرعة
-- الحرة للمقطع نفسه. كمية بلا وحدة تصف «كيف يتصرف هذا الشارع نسبةً
-- إلى طبيعته»، فتنطبق على مقطع لم نمشِ عليه إذا عرفنا سرعته الحرة.
--
-- **القياس الفعلي** (حجز مكاني، 180,940 قياساً على مقاطع لم تُقس):
--   وسيط مطلق:      18.7% خطأ وسيط، p90 = 83.9%، تحيز +6.9%
--   نسبة × حرة:     17.7% خطأ وسيط، p90 = 59.2%، تحيز -0.4%
-- النسبة أفضل في كل مقياس، وأهمها p90: أسوأ 10% من الحالات تحسّنت
-- من 84% خطأ إلى 59%. والتحيز اختفى تقريباً — أي أن التقدير لم يعد
-- يميل منهجياً للتفاؤل.
-- ============================================================

ALTER TABLE class_profiles
    ADD COLUMN IF NOT EXISTS ratio_p10 double precision,
    ADD COLUMN IF NOT EXISTS ratio_p50 double precision,
    ADD COLUMN IF NOT EXISTS ratio_p90 double precision;

COMMENT ON COLUMN class_profiles.ratio_p50 IS
    'وسيط نسبة الأداء (السرعة الفعلية ÷ الحرة) — مرجّح بطول المقطع';
COMMENT ON COLUMN class_profiles.p50_speed IS
    'وسيط السرعة المطلقة كم/س — يبقى للتوافق وللمقارنة';
